package anotacoes.EstruturasSequenciais;

public class Variaveis {
    public static void main(String[] args) {

        // Variaveis - sao espacos na memoria do computador onde podemos armazenar dados, podemos variar ela em qualquer momento do codigo alterando o seu valor

        // Para declarar uma variavel especificamos o seu tipo e depois o seu nome ex:

        int idade; // Podemos declarar uma variavel ainda sem valor e defini-lo logo depois.
        idade = 25; // Dessa forma estamos inicializando a variavel atribuindo valor a ela.

        // Convencoes - Nomes de variaveis devem comecar  com uma letra minuscula e seguir o padrao camelCase.
        // Ex: idade, salarioMensal, nomeCompleto, ganhoTotal, ganhoMensal
    }
}
